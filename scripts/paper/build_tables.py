"""Emit LaTeX tables for the AdaGuard TDSC paper.

Reads JSONs from data/paper_data/ and writes .tex snippets to
paper_artifacts/tables/. Each snippet is a standalone tabular
meant to be \\input{} from the Overleaf source — no preamble,
no \\begin{table} wrapper (so the author can choose placement
and caption).

Usage:
  python scripts/paper/build_tables.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from paper._data import (  # noqa: E402
    REPO_ROOT, DEFENCE_LABELS, DEFENCE_ORDER,
    ATTACK_LABELS, ATTACK_ORDER,
    load_defence_sweep, load_defence_sweep_multiseed, aggregate_multiseed,
    load_v13_random_sweep, aggregate_v13,
    load_consistency, load_client_diversity,
    defence_matrix, best_defence_per_attack,
)

OUT_DIR = REPO_ROOT / "paper_artifacts" / "tables"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def _fmt(v, spec="{:.2f}"):
    if v is None:
        return "--"
    try:
        return spec.format(float(v))
    except (TypeError, ValueError):
        return str(v)


def _bold_if(cell: str, cond: bool) -> str:
    return "\\textbf{" + cell + "}" if cond else cell


# --------------------------------------------------------------------------
# Table III: defence x attack matrix at B=1 (PSNR / LPIPS / ASR)
# --------------------------------------------------------------------------

def build_table_defence_matrix(sweep) -> str:
    grid = defence_matrix(sweep, batch=1)
    # Prefer breaching-backed GradInv if present, else fall back to Geiping recipe.
    use_breaching = any(
        (d, "gradinversion_breaching", 1) in sweep for d in DEFENCE_ORDER
    )
    attacks_ordered = ["gradinversion_breaching" if use_breaching else "gradinversion",
                       "ggcdm", "gi_nas"]

    # Best defence (lowest PSNR) per attack, excluding 'none'.
    grid_for_best = {a: {d: sweep.get((d, a, 1), {}) for d in DEFENCE_ORDER
                         if (d, a, 1) in sweep}
                     for a in attacks_ordered}
    best = best_defence_per_attack(grid_for_best, "psnr", lower_is_better=True)

    lines = [
        "% Auto-generated by scripts/paper/build_tables.py",
        "% Defence x attack matrix at B=1 (iDLG regime).",
        "% Columns: V1 None | V2 FHE | V4 MaskCrypt | V6 AdaGuard-Fisher",
        "\\begin{tabular}{l l S[table-format=2.2] S[table-format=1.3] S[table-format=1.3]}",
        "\\toprule",
        "Attack & Defence & {PSNR (dB)} & {LPIPS} & {Label ASR} \\\\",
        "\\midrule",
    ]

    for attack in attacks_ordered:
        attack_label = ATTACK_LABELS.get(attack, attack)
        for i, defence in enumerate(DEFENCE_ORDER):
            key = (defence, attack, 1)
            if key not in sweep:
                continue
            m = sweep[key]
            psnr = m.get("psnr")
            lpips = m.get("lpips")
            asr = (m.get("label_recovery") or {}).get("asr")
            is_best = (defence == best.get(attack))
            # Bold the best (lowest PSNR) non-trivial cell.
            psnr_str = _fmt(psnr, "{:.2f}")
            lpips_str = _fmt(lpips, "{:.3f}")
            asr_str = _fmt(asr, "{:.3f}")
            if is_best:
                psnr_str = "\\bfseries " + psnr_str
            row_attack = attack_label if i == 0 else ""
            lines.append(
                f"{row_attack} & {DEFENCE_LABELS[defence]} & "
                f"{psnr_str} & {lpips_str} & {asr_str} \\\\"
            )
        lines.append("\\midrule")

    # Trim trailing midrule.
    if lines[-1] == "\\midrule":
        lines[-1] = "\\bottomrule"
    else:
        lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def build_table_defence_matrix_multiseed(multiseed_sweep) -> str:
    """Multi-seed variant: emits ``mean $\\pm$ std`` cells with seed count.

    Prefers ``gradinversion_breaching`` for the GradInv row when any seed
    has it; else falls back to the Geiping-recipe ``gradinversion`` key.
    Cells with a single seed render as the bare value (no ``$\\pm$``).
    """
    summary = aggregate_multiseed(multiseed_sweep)

    # Choose GradInv variant: prefer breaching if any seed has it.
    use_breaching = any(
        (d, "gradinversion_breaching", 1) in multiseed_sweep
        for d in DEFENCE_ORDER
    )
    attacks_ordered = [
        "gradinversion_breaching" if use_breaching else "gradinversion",
        "ggcdm", "gi_nas",
    ]

    # Best defence per attack = lowest mean PSNR across seeds, excluding "none".
    best = {}
    for a in attacks_ordered:
        candidates = {}
        for d in DEFENCE_ORDER:
            if d == "none":
                continue
            cell = summary.get((d, a, 1))
            if not cell:
                continue
            mu = (cell.get("psnr") or {}).get("mean")
            if mu is None:
                continue
            candidates[d] = mu
        if candidates:
            best[a] = min(candidates, key=candidates.get)

    # Inspect total seed coverage so the caption note is accurate.
    seeds_seen = set()
    for by_seed in multiseed_sweep.values():
        seeds_seen.update(by_seed.keys())
    n_seeds = len(seeds_seen)

    def _ms(cell, key, spec):
        info = (cell or {}).get(key) or {}
        mu = info.get("mean")
        sd = info.get("std")
        n = info.get("n", 0)
        if mu is None:
            return "--"
        if n <= 1:
            return spec.format(mu)
        return f"{spec.format(mu)} $\\pm$ {spec.format(sd)}"

    seed_list = ", ".join(f"seed {s}" for s in sorted(seeds_seen, key=lambda x: int(x)))
    lines = [
        "% Auto-generated by scripts/paper/build_tables.py",
        f"% Defence x attack matrix at B=1, multi-seed ({n_seeds} seeds: {seed_list}).",
        "% Cells are mean $\\pm$ std across seeds; single-seed cells omit std.",
        "% Columns: V1 None | V2 FHE | V4 MaskCrypt | V6 AdaGuard-Fisher",
        "\\begin{tabular}{l l c c c}",
        "\\toprule",
        "Attack & Defence & PSNR (dB) & LPIPS & Label ASR \\\\",
        "\\midrule",
    ]
    for attack in attacks_ordered:
        attack_label = ATTACK_LABELS.get(attack, attack)
        # Build all rows for this attack (skip if no data at all).
        attack_rows = []
        for i, defence in enumerate(DEFENCE_ORDER):
            cell = summary.get((defence, attack, 1))
            if not cell:
                continue
            psnr_str = _ms(cell, "psnr", "{:.2f}")
            lpips_str = _ms(cell, "lpips", "{:.3f}")
            asr_str = _ms(cell, "asr", "{:.3f}")
            if defence == best.get(attack) and psnr_str != "--":
                psnr_str = "\\textbf{" + psnr_str + "}"
            row_attack = attack_label if not attack_rows else ""
            attack_rows.append(
                f"{row_attack} & {DEFENCE_LABELS[defence]} & "
                f"{psnr_str} & {lpips_str} & {asr_str} \\\\"
            )
        if attack_rows:
            lines.extend(attack_rows)
            lines.append("\\midrule")

    # Trim trailing midrule.
    if lines[-1] == "\\midrule":
        lines[-1] = "\\bottomrule"
    else:
        lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


